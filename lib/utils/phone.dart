/// Калиди ягона барои муқоисаи рақамҳои телефон.
///
/// Дар китобчаи телефон як рақам дар шаклҳои гуногун навишта мешавад:
/// `+992 97 405 5566`, `992974055566`, `97 405 5566`, `0974055566`.
/// Дар Firestore бошад ҳамеша дар шакли `+992974055566` нигоҳ дошта мешавад.
/// Барои он ки ҳамаи инҳо як шахс ҳисоб шаванд, танҳо рақамҳоро мегирем ва
/// 9 рақами охирро (рақами миллӣ бе коди кишвар) муқоиса мекунем.
///
/// Рақамҳои аз 7 рақам кӯтоҳтар (масалан рамзҳои хидматӣ) калиди холӣ
/// мегиранд, то тасодуфан ба касе мувофиқ наоянд.
String phoneMatchKey(String raw) {
  final digits = raw.replaceAll(RegExp(r'[^0-9]'), '');
  if (digits.length < 7) return '';
  return digits.length <= 9 ? digits : digits.substring(digits.length - 9);
}
